					then
						echo "$date: It's an IPV4 address." >> $Logfile
						echo "$date: It's an IPV4 address." >> $Logfile2
						break
					else
						echo "$date: The IPv4 address obtained is incorrect. It has '$ipaddr' dots." >> $Logfile
						echo "$date: The IPv4 address obtained is incorrect. It has '$ipaddr' dots." >> $Logfile2
						#Reboot/switch sim depending on the interface name.
						#ModemReboot $InterfaceName $ComPortSymLink
					fi
				
				#For ipv6 -
				elif [ "$pdp" = "2" ]
				then
				
					ipaddr_obtained=$(echo $Status | cut -d "," -f 4 | tr -d '\011\012\013\014\015\040')
					ipaddr=$(echo $Status | cut -d "," -f 4 | cut -d ":" -f 1 | awk -F'"' '{print $2}' | tr -d '\011\012\013\014\015\040')
					
					echo "$date: The IP address is - $ipaddr_obtained" >> $Logfile
					echo "$date: The IP address is - $ipaddr_obtained" >> $Logfile2
					
					#ipv6 starting addr should be greater then 2000                         
					if [ "$ipaddr" -gt "2000" ]                                                                                                        
					then
						echo "$date: It's an IPV6 address." >> $Logfile
						echo "$date: It's an IPV6 address." >> $Logfile2
						break
					else
						echo "$date: The IPv6 address obtained is incorrect. It has '$ipaddr' starting address." >> $Logfile
						echo "$date: The IPv6 address obtained is incorrect. It has '$ipaddr' starting address." >> $Logfile2
						#Reboot/switch sim depending on the interface name.
						#ModemReboot $InterfaceName $ComPortSymLink
					fi
				
				#For ipv4v6 -
				elif [ "$pdp" = "3" ]
				then
					
					Status=$(at-cmd "$ComPortSymLink" at+cgpaddr=1 | tr -d '\011\012\013\014\015\040')
					
					#For ipv4 address					
					ipaddr1=$(echo $Status | cut -d "," -f 2 | tr -d -c '.' | wc -c | tr -d '\011\012\013\014\015\040')

					# Extracting the IPv6 address in decimal format
					ipv6_decimal=$(echo $Status | cut -d "," -f 3)

					# Extracting the first two numbers of the decimal IPv6 address
					first_two_numbers_decimal=$(echo $ipv6_decimal | cut -d "." -f 1-2)

					# Converting the decimal numbers to hexadecimal
					ipaddr2=$(echo $first_two_numbers_decimal | awk '{ printf "%02X%02X", $1, $2 }')
					
					#ipv6 starting addr should be greater then 2000 & ipv4 has 3 dots (.)                        
					if [ "$ipaddr1" = "3" ] && [ "$ipaddr2" -gt "2000" ]                                                
					then
						echo "$date: It's an IPV4V6 address" >> $Logfile
						echo "$date: It's an IPV4V6 address" >> $Logfile2
						break
					else
						echo "$date: The IPv6 address obtained is incorrect. It has '$ipaddr1' dots & '$ipaddr2' starting address." >> $Logfile
						echo "$date: The IPv6 address obtained is incorrect. It has '$ipaddr1' dots & '$ipaddr2' starting address." >> $Logfile2
						#Reboot/switch sim depending on the interface name.
						#ModemReboot $InterfaceName $ComPortSymLink
					fi
				
				#For wrong pdp
				else
					echo "$date: Wrong pdp set. Rebooting ..." >> $Logfile
					echo "$date: Wrong pdp set. Rebooting ..." >> $Logfile2
					#Reboot/switch sim depending on the interface name.
					ModemReboot $InterfaceName $ComPortSymLink
					
					#Exit if the AddIfaceRunningstatus2 flag is set to 1. 
					CheckAddIfaceRunningstatus2
				fi                                                                                                                         
			done
		fi
	fi
}

