		else
			#check if pdp is activated/not.
			for i in 1 2 3                                                                                                                    
			do	
				#To get only IP we use here (cut -d "," -f 4)
				Status=$(/bin/at-cmd $ComPortSymLink AT+QIACT? | awk NR==2 | cut -d "," -f 4 | tr -d '\011\012\013\014\015\040')
