# Function to check if a GPIO exists
check_gpio_existence() {
    local gpio="$1"
    if [ -d "/sys/class/gpio/gpio$gpio" ]; then
		echo "<AddInterface.sh><check_gpio_existence>GPIO $gpio exists" >> $Logfile2
        return 0  # GPIO exists
    else
		echo "<AddInterface.sh><check_gpio_existence>GPIO $gpio doesn't exists" >> $Logfile2
        return 1  # GPIO does not exist
    fi
}

#SIM LEDS
SimLeds(){
	
	InterfaceName="$1"
	status="$2"

	# Check and export Sim1LedGpio if it doesn't exist
	if ! check_gpio_existence "$Sim1LedGpio"; then
		echo "$Sim1LedGpio" > /sys/class/gpio/export
		echo out > "/sys/class/gpio/gpio$Sim1LedGpio/direction"
		echo "<AddInterface.sh><SimLeds>Exported and configured $Sim1LedGpio" >> $Logfile2
	fi

	# Check and export Sim2LedGpio if it doesn't exist
	if ! check_gpio_existence "$Sim2LedGpio"; then
		echo "$Sim2LedGpio" > /sys/class/gpio/export
		echo out > "/sys/class/gpio/gpio$Sim2LedGpio/direction"
		echo "<AddInterface.sh><SimLeds>Exported and configured $Sim2LedGpio" >> $Logfile2
	fi

}

