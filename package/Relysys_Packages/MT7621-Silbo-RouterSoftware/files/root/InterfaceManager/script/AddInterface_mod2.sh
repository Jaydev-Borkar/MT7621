#Calling this function everytime after ModemReboot Function is called.
CheckAddIfaceRunningstatus2()
{
	#Exit if the AddIfaceRunningstatus2 flag is set to 1. 
	source /tmp/AddIfaceRunningstatus2
	if [ "$AddIfaceRunningstatus2" = "1" ] 
	then 
		exit 0
	fi
}
#
# Search for Communication & data port and write the same into file 
#
PortSearch()
{
	InterfaceName="$1"
	ConfiguredComPort="$2"
	IPV6InterfaceName="$3"
	
	# Search for symbolically linked ports(generated by udev rule) and copy the same
	ComPortSymLink=$(find /dev -maxdepth 1 -name  "$InterfaceName""_"* | sort | sed -n $ConfiguredComPort"p")
	AltComPortSymLink=$(find /dev -maxdepth 1 -name  "$InterfaceName""_"* | sort | sed -n $ConfiguredAltComPort"p")
	
	sleep 1
	
	#Add ComPortSymLink to modem & sysconfig file. Can be used in any gcom script or in systemstart script.
	if [ "$1" = "CWAN2" ]
	then
		a="2"
	else
		a="1"
	fi
	uci set modem.$1.ComPortSymLink=$ComPortSymLink
	uci set sysconfig.sysconfig.ComPortSymLink$a=$ComPortSymLink
	uci set modem.$1.AltComPortSymLink=$AltComPortSymLink
	uci set sysconfig.sysconfig.AltComPortSymLink$a=$AltComPortSymLink
	uci commit modem
	uci commit sysconfig
	
	sleep 2
	
	echo "<AddInterface_mod2.sh> <PortSearch> The ComPortSymLink for $1=$ComPortSymLink" >> $Logfile2
	
	echo "ComPortSymLink=$ComPortSymLink" > "$PortDetailsFile"
	echo "ComPort=$ComPortSymLink" >> "$PortDetailsFile"
	
	if [ "x$ComPortSymLink" = "x" ]
	then
		echo "status=ComPortLink NE" >> "$PortDetailsFile"
		echo "status=Disabled" > "$AddIfaceStatusFile"
	else
		if [ "$EnableCellular" = "1" ]
		then
			echo "<AddInterface_mod2.sh> <PortSearch> EnableCellular set to 1. " >> $Logfile2
			#Check if the file doesn't exist. This is required during boot because
			#At command sim switch doesn't reset back to sim 1 when modem is rebooted.
			#If this file is there, then, don't run the AT command for sim switch.
			if [ ! -e /tmp/checksimswitch.txt ]
			then
				#Set rm500 and em06 to sim1.
				model=$(uci get modem.$InterfaceName.model)
				
				echo "<AddInterface_mod2.sh> <PortSearch> The modem is = $model" >> $Logfile2
				
				for i in 1 2 3
				do
					#RM500Q & RM500U uses 1 for sim1 and 2 for sim2
					if [ $model = "RM500U" ] || [ $model = "RM500Q" ]
					then
						
						#Just fire one AT command.
						/bin/at-cmd $ComPortSymLink AT
						
						sleep 1
												
						for j in 1 2 3 4
						do	
							Status=$(/bin/at-cmd $ComPortSymLink AT+QUIMSLOT?)
							
							# Extract QUIMSLOT value using awk
							quimslot=$(echo "$Status" | awk '/\+QUIMSLOT:/ {print $2}')

							# Extract OK response
							ok_response=$(echo "$Status" | grep -o 'OK[[:space:]]*$')
							
							# If the value obtained is 1; break.
							if [ "$quimslot" = "1" ]
							then
								echo "<AddInterface_mod2.sh> <PortSearch> On bootup sim switch set to 1. " >> $Logfile2
								done=1
								break
							
							#If the value obtained is 2; then set to sim 1 & reboot the modem.
							elif [ "$quimslot" = "2" ]
							then
								echo "<AddInterface_mod2.sh> <PortSearch> On bootup sim switch is set to 2. " >> $Logfile2
								
								for k in 1 2 3
								do
									echo "<AddInterface_mod2.sh> <PortSearch> Setting the sim to 1. " >> $Logfile2
									
									/bin/at-cmd $ComPortSymLink AT+QUIMSLOT=1
									
									sleep 2
									
									#Create /tmp/checksimswitch.txt, so it sets to sim1 only on boot up & not everytime. 
									touch /tmp/checksimswitch.txt
									
									#Now, reboot the modem.
									if [ "$InterfaceName" = "CWAN1" ] || [ "$InterfaceName" = "CWAN1_0" ] || [ "$InterfaceName" = "CWAN1_1" ]
									then
										echo "<AddInterface_mod2.sh> <PortSearch> Rebooting $InterfaceName after setting simswitch to FIRST sim..." >> $Logfile2
										/root/usrRPC/script/Recycle_WAN1_PWR_Script.sh $ComPortSymLink & 
										exit 0
									elif [ "$InterfaceName" = "CWAN2" ]
									then
										#Setting AddIfaceRunningstatus2 to 1. That is, Donot allow AddInterface to run.
										echo "AddIfaceRunningstatus2=1" > /tmp/AddIfaceRunningstatus2
										
										echo "<AddInterface_mod2.sh> <PortSearch> Rebooting $InterfaceName after setting simswitch to FIRST sim..." >> $Logfile2
										
										/root/usrRPC/script/Recycle_WAN2_PWR_Script.sh $ComPortSymLink &
										exit 0
									fi
								done
							
							#If the value obtained is neither 1 or 2; that is, some junk response, then, check once again.	
							else
								sleep 2
							fi
						done
						
						if [ "$done" = "1" ]
						then
							echo "<AddInterface_mod2.sh> <PortSearch> Sim switch is ALREADY set to 1. " >> $Logfile2
							break
						fi
						
					#EM06 uses 0 for sim1 and 1 for sim2
					elif [ $model = "EM06" ]
					then
						/bin/at-cmd $ComPortSymLink AT+QDSIM=0
					fi
				done
				
				#Create /tmp/checksimswitch.txt, so it sets to sim1 only on boot up & not everytime. 
				touch /tmp/checksimswitch.txt
				
				#Create /tmp/onboot_modemsimswitch.txt, so that the below simcheck after qccid doesn't happen; 
				#since, simnum is always set to 1 on bootup. 
				touch /tmp/modemsimswitch.txt
				
			fi
			
			echo "<AddInterface_mod2.sh> <PortSearch> Checking for qccid ..." >> $Logfile2
			
			#Now get the qccid.
			for i in 1 2 3 4
			do
				simid=$(/usr/bin/gcom -d "$ComPortSymLink" -s "$QccidScript" | awk FNR==2 | cut -d ":" -f 2 | tr -d '\011\012\013\014\015\040')
				
				echo "<AddInterface_mod2.sh> <PortSearch> simid is - $simid" >> $Logfile2
				
				#####################################################################
				#1.07-RC7
				#Added the below for ReadSIMInfo to show the qccid in the others page.
				touch tmp/sim2info.txt 
				echo "Modem 2 QCCID = $simid" > /tmp/sim2info.txt
				#####################################################################
				
				#Check if the simid is just numbers. This is to reject anyother AT cmd response apart from qccid.
				#if  echo "$simid" | grep -q '^[0-9]*$'
				#then
					#Now check, if it's greater than 20 numbers.
					if [ "${#simid}" -gt 10 ]
					then
						status="READY"
					break
					else
						status="NOTREADY"
					fi
				#fi
			done
			
			echo " " >> $Logfile
			echo " " >> $Logfile
			echo "==================================================================" >> $Logfile
			echo "============ $date: $InterfaceName -- $ComPortSymLink ============" >> $Logfile
			echo " " >> $Logfile
			
			#Check if the file modemsimswitch doesn't exist. If there is no modemsimswitch.txt, then this is the 1st bootup.
			#It means, the above simnum check on bootup has been run already. Hence, no need to run the below simcheck twice.
			#since, simnum is always set to 1 on bootup. If the file isn't there, then, break.
			
			if [ ! -e /tmp/modemsimswitch.txt ]
			then
				echo "<AddInterface_mod2.sh> <PortSearch> modemsimswitch.txt is not present. Create it and then break! " >> $Logfile2
				#Creating the file for 1st bootup
				touch /tmp/modemsimswitch.txt 
				#If the file isn't there, then, break. On bootup simnum check has been executed already.
				break
			else
				echo "<AddInterface_mod2.sh> <PortSearch> modemsimswitch.txt is present." >> $Logfile2
				#Check if modemsimnum is same as simnum.
				simnum=$(cat /tmp/simnumfile)
				
				model=$(uci get modem.$InterfaceName.model)
				
				#RM500Q & RM500U uses 1 for sim1 and 2 for sim2
				if [ $model = "RM500U" ] || [ $model = "RM500Q" ]
				then
					echo "<AddInterface_mod2.sh> <PortSearch> For $model, checking if modemsimnum is same as simnum." >> $Logfile2
					
					#Just fire one AT command.
					/bin/at-cmd $ComPortSymLink AT
					
					sleep 1
					
					#Get the QUIMSLOT value 						
					for i in 1 2 3 4
					do	
						Status=$(/bin/at-cmd $ComPortSymLink AT+QUIMSLOT?)
						
						# Extract QUIMSLOT value using awk
						quimslot=$(echo "$Status" | awk '/\+QUIMSLOT:/ {print $2}')
						
						if [ "$quimslot" = "1" ] || [ "$quimslot" = "2" ]
						then
							#Set got_resp as 1, if received response. So as not to switch to alt comport port.
							got_resp=1
							break
						else
							sleep 2
						fi
					done
					
					if [ "$got_resp" = "1" ]
					then
						break
					
					#If no response on comport, then switch to alt comport.
					else
						echo "$date: No response on AT+QUIMSLOT?; switching to alternate comport" >> $Logfile1
						
						for i in 1 2 3 4
						do	
							Status=$(/bin/at-cmd $AltComPortSymLink AT+QUIMSLOT?)
							
							# Extract QUIMSLOT value using awk
							quimslot=$(echo "$Status" | awk '/\+QUIMSLOT:/ {print $2}')
							
							if [ "$quimslot" = "1" ] || [ "$quimslot" = "2" ]
							then
								break
							else
								sleep 2
							fi
						done
						
					fi	
						
					#For dualcellularsinglesim, just make sure that the modem isn't set to sim2.
					if [ "$CellularOperationModelocal" = "dualcellularsinglesim" ]
					then
						if [ $model = "RM500U" ] || [ $model = "RM500Q" ]
						then
							simnum="1"
						fi
					fi
						
					# If the MODEMSIMNUM is same as SIMNUM; break.
					if [ "$quimslot" = "$simnum" ]
					then
						echo "<AddInterface_mod2.sh> <PortSearch> MODEMSIMNUM=$quimslot; SIMNUM=$simnum. " >> $Logfile2
						echo "<AddInterface_mod2.sh> <PortSearch> MODEMSIMNUM is same as SIMNUM. " >> $Logfile2

						break
					
					# If the MODEMSIMNUM is DIFFERENT than SIMNUM; Take simnum as priority & do simswitch.
					else
						echo "<AddInterface_mod2.sh> <PortSearch> MODEMSIMNUM=$quimslot; SIMNUM=$simnum. " >> $Logfile2
						echo "<AddInterface_mod2.sh> <PortSearch> MODEMSIMNUM is DIFFERENT than SIMNUM. " >> $Logfile2
						echo "<AddInterface_mod2.sh> <PortSearch> Setting the sim to $simnum. " >> $Logfile2
						
						for j in 1 2 3
						do	
							/bin/at-cmd $ComPortSymLink AT+QUIMSLOT=$simnum
							
							sleep 2
						done
						
						#Now, reboot the modem.
						if [ "$InterfaceName" = "CWAN1_0" ] || [ "$InterfaceName" = "CWAN1_1" ]
						then
							echo "<AddInterface_mod2.sh> <PortSearch> Rebooting $InterfaceName after setting modemsimnum to $simnum..." >> $Logfile2
							/root/usrRPC/script/Recycle_WAN1_PWR_Script.sh $ComPortSymLink & 
							exit 0
						fi
					fi
				fi
			fi
			
			#If status = READY
			if [ "$status" = "READY" ]
			then
				
				echo "$date: The QCCID is - $simid" >> $Logfile
				echo "$date: The status is - $status" >> $Logfile
				echo " " >> $Logfile
				
				echo "$date: The QCCID is - $simid" >> $Logfile2
				echo "$date: The status is - $status" >> $Logfile2
				
				#Values are set in /etc/config/modemstatus for snmp agent
				uci set modemstatus.modemstatus=interface
				uci set modemstatus.modemstatus.PinState2=$status
				uci set modemstatus.modemstatus.QCCID2=$simid
				uci commit modemstatus
				
				
				# /tmp/simnotready file is created when the status is not ready and deleted if the status is ready.
				# If this file is present, /bin/checkinterfaces.sh doesn't run during systemboot.sh
				rm /tmp/simnotready
				
				#Add network config if sim is ready.
				AddNetworkInterface $InterfaceName $status $IPV6InterfaceName
			
			#If status = NOTREADY
			else
				
				echo "$date: The QCCID is - $simid & the status is - $status" >> $Logfile
				echo "$date: The QCCID is - $simid" >> $Logfile2
				echo "$date: The status is - $status" >> $Logfile2
				
				#Values are set in /etc/config/modemstatus for snmp agent
				uci set modemstatus.modemstatus=interface
				uci set modemstatus.modemstatus.PinState2=$status
				uci set modemstatus.modemstatus.QCCID2=$simid
				uci commit modemstatus
				
				# /tmp/simnotready file is created when the status is not ready and deleted if the status is ready.
				# If this file is present, /bin/checkinterfaces.sh doesn't run during systemboot.sh
				
				touch /tmp/simnotready
				
				if [ "$InterfaceName" = "CWAN1" ]
				then
					#sleep for 2 minutes and reboot the modem. This will go on until it detects qccid.
					
					echo "Rechecking if the $InterfaceName is up in 120 seconds ..." >> $Logfile2
					
					sleep 120
					
					echo "checking Qccid Info ..." >> $Logfile2
					
					QccidInfo
					
					if [ "$status_info" = "NOTREADY" ]
					then
						
						echo "The Qccid status is still not ready. Hence, rebooting." >> $Logfile2
						
						/root/usrRPC/script/Recycle_WAN1_PWR_Script.sh $ComPortSymLink
					fi
					
				elif [ "$InterfaceName" = "CWAN2" ]
				then
					#sleep for 2 minutes and reboot the modem. This will go on until it detects qccid.
					
					echo "Rechecking if the $InterfaceName is up in 120 seconds ..." >> $Logfile2
					
					sleep 120
					
					#Exit if the AddIfaceRunningstatus2 flag is set to 1. 
					CheckAddIfaceRunningstatus2

					echo "checking Qccid Info ..." >> $Logfile2
					
					QccidInfo
					
					#Exit if the AddIfaceRunningstatus2 flag is set to 1. 
					CheckAddIfaceRunningstatus2

					if [ "$status_info" = "NOTREADY" ]
					then
					
						echo "The Qccid status is still not ready. Hence, rebooting." >> $Logfile2
						
						#Setting AddIfaceRunningstatus2 to 1. That is, Donot allow AddInterface to run.
						echo "AddIfaceRunningstatus2=1" > /tmp/AddIfaceRunningstatus2
						
						/root/usrRPC/script/Recycle_WAN2_PWR_Script.sh $ComPortSymLink

						#Exit if the AddIfaceRunningstatus2 flag is set to 1. 
						CheckAddIfaceRunningstatus2
					fi
				fi
				
				if [ "$InterfaceName" = "CWAN1_0" ]
				then
					echo "The Qccid status is not ready. Hence, switching to sim 2." >> $Logfile2
					
					/root/InterfaceManager/script/SimSwitch.sh CWAN1 2
					if [ "$PrimarySimSwitchBackEnable" = "1" ]
					then
						pid=$(pgrep -f "/root/InterfaceManager/script/PrimarySwitch.sh")
						kill -TERM "$pid" > /dev/null 2>&1
						sleep 1
						kill -KILL "$pid" > /dev/null 2>&1
						/root/InterfaceManager/script/PrimarySwitch.sh "$PrimarySimSwitchBackTime" CWAN1 1 &         
					fi
				fi
				if [ "$InterfaceName" = "CWAN1_1" ]
				then
					echo "The Qccid status is not ready. Hence, switching to sim 1." >> $Logfile2
					/root/InterfaceManager/script/SimSwitch.sh CWAN1 1
				fi
			fi
		fi
		
	#For qnetdevctl.sh.
	echo "0" > /tmp/qnetdevctl2
		
	fi 
	      
}

