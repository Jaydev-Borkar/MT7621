ModemReboot() {
	InterfaceName=$1
	ComPortSymLink=$2
	
	echo "$date: Rebooting $InterfaceName ..." >> $Logfile2
	#Setting AddIfaceRunningstatus2 to 1. That is, Donot allow AddInterface to run.
	echo "AddIfaceRunningstatus2=1" > /tmp/AddIfaceRunningstatus1
	
	if [ "$InterfaceName" = "CWAN1" ]
	then
		echo "$date: Rebooting CWAN1 ..." >> $Logfile
		echo "<AddInterface_mod2.sh> <ModemReboot> Rebooting CWAN1 ..." >> $Logfile2
		echo 1 > "$SimNumFile"
		/root/usrRPC/script/Recycle_WAN1_PWR_Script.sh $ComPortSymLink & 
		break
	elif [ "$InterfaceName" = "CWAN2" ]
	then
		echo "$date: Rebooting CWAN2 ..." >> $Logfile
		echo "<AddInterface_mod2.sh> <ModemReboot> Rebooting CWAN2 ..." >> $Logfile2
		/root/usrRPC/script/Recycle_WAN2_PWR_Script.sh $ComPortSymLink & 
		break
	elif [ "$InterfaceName" = "CWAN1_0" ]
	then
		echo "$date: Rebooting CWAN1_0 ..." >> $Logfile
		echo "<AddInterface_mod2.sh> <ModemReboot> Rebooting CWAN1_0 ..." >> $Logfile2
		echo 1 > "$SimNumFile"
		/root/usrRPC/script/Recycle_WAN1_PWR_Script.sh $ComPortSymLink & 
		break
		
	elif [ "$InterfaceName" = "CWAN1_1" ]
	then
		echo "$date: Rebooting CWAN1_1 ..." >> $Logfile
		echo "<AddInterface_mod2.sh> <ModemReboot> Rebooting CWAN1_1 ..." >> $Logfile2
		
		#If the modem works on sim2, then sim2 should be up, not sim1.
		/root/InterfaceManager/script/SimSwitch.sh CWAN1 2
		if [ "$PrimarySimSwitchBackEnable" = "1" ]
		then
			pid=$(pgrep -f "/root/InterfaceManager/script/PrimarySwitch.sh")
			kill -TERM "$pid" > /dev/null 2>&1
			sleep 1
			kill -KILL "$pid" > /dev/null 2>&1
			/root/InterfaceManager/script/PrimarySwitch.sh "$PrimarySimSwitchBackTime" CWAN1 1 &         
		fi
		break
	fi
	exit 0
}

SetATCommands() {
	
	#Exit if the AddIfaceRunningstatus2 flag is set to 1. 
	CheckAddIfaceRunningstatus2
	
	date=$(date) 
	
	InterfaceName=$1
	ComPortSymLink=$2
	
	model=$(uci get modem.$InterfaceName.model)
	AltComPortSymLink=$(uci get modem.$InterfaceName.AltComPortSymLink)
	
	echo "------ $date: SetATCommands $InterfaceName -- $ComPortSymLink ------" >> $Logfile
	echo "<AddInterface_mod2.sh><SetATCommands> $InterfaceName -- $ComPortSymLink" >> $Logfile2
	
	#To check sim status. It should come ready. It should come within 20 sec
	for i in 1 2 3                                                                                                                  
	do 
		Status=$(/bin/at-cmd "$ComPortSymLink" AT+CPIN? | awk NR==2 | cut -d ":" -f 2 | tr -d '\011\012\013\014\015\040')
		if [ $Status = "READY" ]
		then
			echo "$date:AT+CPIN=$Status,CPIN is Ready" >> $Logfile
			echo "$date:AT+CPIN=$Status,CPIN is Ready" >> $Logfile2
			break
		else
			sleep 3
		fi
	done
	
	if [ "$Status" != "READY" ]
	then
		echo "$date:[AT+CPIN=$Status]CPIN is not Ready. Hence, checking on AltComPort." >> $Logfile
		echo "$date:[AT+CPIN=$Status]CPIN is not Ready. Hence, checking on AltComPort." >> $Logfile2
		
		for i in 1 2 3                                                                                                                  
		do
		
			Status_Alt=$(/bin/at-cmd "$AltComPortSymLink" AT+CPIN? | awk NR==2 | cut -d ":" -f 2 | tr -d '\011\012\013\014\015\040')
			if [ "$Status_Alt" = "READY" ]
			then
				echo "$date:AT+CPIN=$Status,CPIN is Ready" >> $Logfile
				echo "$date:AT+CPIN=$Status,CPIN is Ready" >> $Logfile2
				break
			else
				sleep 3
			fi
		done
		
		if [ "$Status_Alt" != "READY" ]
		then
			echo "$date:[AT+CPIN=$Status]CPIN is not Ready. Hence, rebooting." >> $Logfile
			echo "$date:[AT+CPIN=$Status]CPIN is not Ready. Hence, rebooting." >> $Logfile2
			
			#Reboot/switch sim depending on the interface name.
			ModemReboot $InterfaceName $ComPortSymLink
			
			#Exit if the AddIfaceRunningstatus2 flag is set to 1. 
			CheckAddIfaceRunningstatus2
		fi
	fi
	
	#Doesn't work for RM500U. So, skip it.
	if [ $model != "RM500U" ]
	then
	
		#To check if it is registered in circuit switched network. should happen within 90 sec.
		#output should be 0,1.
		for i in 1 2 3                                                                                                                  
		do 
			Status=$(/bin/at-cmd "$ComPortSymLink" AT+CREG? | awk NR==2 | cut -d ":" -f 2 | cut -d "," -f 2 | tr -d '\011\012\013\014\015\040')

			if [ $Status = "1" ]
			then
				echo "$date:[AT+CREG?=$Status]Sim is Successfully Registered" >> $Logfile
				echo "$date:[AT+CREG?=$Status]Sim is Successfully Registered" >> $Logfile2
				break
			else
				sleep 3
			fi
		done
		
		if [ "$Status" != "1" ]
		then
			echo "$date:[AT+CREG?=$Status]Sim is not Successfully Registered" >> $Logfile
			echo "$date:[AT+CREG?=$Status]Sim is not Successfully Registered" >> $Logfile2
		fi
		
		#To check Registration status.
		#output should be 0,1.
		for i in 1 2 3                                                                                                                  
		do 
			Status=$(/bin/at-cmd "$ComPortSymLink" AT+CGREG? | awk NR==2 | cut -d ":" -f 2 | cut -d "," -f 2 | tr -d '\011\012\013\014\015\040')

			if [ $Status = "1" ]
			then
				echo "$date: The sim is registered for AT+CGREG & the status is ="$Status >> $Logfile
				echo "$date: The sim is registered for AT+CGREG & the status is =$Status" >> $Logfile2
				break
			else
				sleep 3
			fi
		done
		
		if [ "$Status" != "1" ]
		then
			echo "$date: The sim is NOT registered for AT+CGREG & the status is ="$Status >> $Logfile
			echo "$date: The sim is 'NOT' registered for AT+CGREG & the status is =$Status" >> $Logfile2
			#Reboot/switch sim depending on the interface name.
			#ModemReboot $InterfaceName $ComPortSymLink
		fi
	fi
	
	#Check AT+COPS?
	for i in 1 2                                                                                                                 
	do
		echo "$date: Checking for AT+COPS?" >> $Logfile
		echo "$date: Checking for AT+COPS?" >> $Logfile2
		Status=$(/bin/at-cmd $ComPortSymLink AT+COPS? | sed -n '2p' | tr -d '\011\012\013\014\015\040') 
		
		if [ "$Status" = "+COPS: 0" ]                                                                                                        
		then
			echo "$date: The status of AT+COPS? is $Status. Hence, rebooting ..." >> $Logfile
			echo "$date: The status of AT+COPS? is $Status. Hence, rebooting ..." >> $Logfile2

			#Reboot/switch sim depending on the interface name.
			ModemReboot $InterfaceName $ComPortSymLink
			
			#Exit if the AddIfaceRunningstatus2 flag is set to 1. 
			CheckAddIfaceRunningstatus2
			
			break                                                                                                                     
		elif [ -z "$Status" ]
		then
			echo "$date: The status of AT+COPS? is unavailable. Hence, checking on AltComPort." >> $Logfile
			echo "$date: The status of AT+COPS? is unavailable. Hence, checking on AltComPort." >> $Logfile2
			
			Status_alt=$(/bin/at-cmd $AltComPortSymLink AT+COPS? | sed -n '2p' | tr -d '\011\012\013\014\015\040')
			
			echo "$date: The status of AT+COPS? is $Status_alt." >> $Logfile
			echo "$date: The status of AT+COPS? is $Status_alt." >> $Logfile2
			
			if [ "$Status_alt" = "+COPS: 0" ]                                                                                                        
			then
				echo "$date: The status of AT+COPS? is $Status_alt. Hence, rebooting ..." >> $Logfile
				echo "$date: The status of AT+COPS? is $Status_alt. Hence, rebooting ..." >> $Logfile2

				#Reboot/switch sim depending on the interface name.
				ModemReboot $InterfaceName $AltComPortSymLink
				
				#Exit if the AddIfaceRunningstatus2 flag is set to 1. 
				CheckAddIfaceRunningstatus2
				
				break
			else
				echo "$date: The status of AT+COPS? is $Status_alt." >> $Logfile
				echo "$date: The status of AT+COPS? is $Status_alt." >> $Logfile2
				break
			fi
		else
			echo "$date: The status of AT+COPS? is $Status." >> $Logfile
			echo "$date: The status of AT+COPS? is $Status." >> $Logfile2
			break
		fi
	done 
	
	#Check for the set pdp, APN & authentication. 
	for i in 1 2                                                                                                                 
	do
		Status=$(/bin/at-cmd $ComPortSymLink AT+QICSGP=1 | awk NR==2 | awk '{print $2}' | tr -d '\011\012\013\014\015\040')
		pdp_stat=$(echo $Status | awk -F',' '{print $1}' | tr -d '\011\012\013\014\015\040')                           
		apn_stat=$(echo $Status | awk -F',' '{print $2}' | awk -F'"' '{print $2}' | tr -d '\011\012\013\014\015\040')                           
		auth_stat=$(echo $Status | awk -F',' '{print $5}' | tr -d '\011\012\013\014\015\040') 
		if [ ! -n "$Status" ]                                                                                                        
		then                                                                                                                           
			sleep 1                                                                                                                     
		else                                                                                                                           
			break                                                                                                                    
		fi                                                                                                                             
	done 
	
	echo "$date: The status obtained for AT+QICSGP cmd is = "$Status >> $Logfile
	echo "$date: The Default PDP set in modem is = $pdp_stat" >> $Logfile
	echo "$date: The Required PDP is = $pdp" >> $Logfile
	echo "$date: The Default APN set in modem is = $apn_stat" >> $Logfile
	echo "$date: The Required APN is = $APN" >> $Logfile
	echo "$date: The Default Auth is set in modem= $auth_stat" >> $Logfile
	echo "$date: The Required Auth is = $auth" >> $Logfile
	
	echo "$date: The status obtained for AT+QICSGP cmd is = "$Status >> $Logfile2
	echo "$date: The Default PDP set in modem is = $pdp_stat" >> $Logfile2
	echo "$date: The Required PDP is = $pdp" >> $Logfile2
	echo "$date: The Default APN set in modem is = $apn_stat" >> $Logfile2
	echo "$date: The Required APN is = $APN" >> $Logfile2
	echo "$date: The Default Auth is set in modem= $auth_stat" >> $Logfile2
	echo "$date: The Required Auth is = $auth" >> $Logfile2
	
	#If status is empty.
	if [ ! -n "$Status" ]
	then
		echo "$date: The status is empty for AT+QICSGP cmd. Hence, checking on AltComPort." >> $Logfile
		echo "$date: The status is empty for AT+QICSGP cmd. Hence, checking on AltComPort." >> $Logfile2
		
		for i in 1 2                                                                                                                 
		do
			Status_Alt=$(/bin/at-cmd $AltComPortSymLink AT+QICSGP=1 | awk NR==2 | awk '{print $2}' | tr -d '\011\012\013\014\015\040')
			if [ ! -n "$Status_Alt" ]                                                                                                        
			then                                                                                                                           
				sleep 1                                                                                                                     
			else                                                                                                                           
				break                                                                                                                    
			fi                                                                                                                             
		done 
		
		pdp_stat=$(echo $Status_Alt | awk -F',' '{print $1}' | tr -d '\011\012\013\014\015\040')                           
		apn_stat=$(echo $Status_Alt | awk -F',' '{print $2}' | awk -F'"' '{print $2}' | tr -d '\011\012\013\014\015\040')                           
		auth_stat=$(echo $Status_Alt | awk -F',' '{print $5}' | tr -d '\011\012\013\014\015\040')
	fi	
	
	#If the pdp, APN & authentication are different, only then, set them using QICSGP command.
	if [ "$pdp_stat" != "$pdp" ] || [ "$apn_stat" != "$APN" ] || [ "$auth_stat" != "$auth" ]
	then
		echo "$date: pdp, APN & authentication are DIFFERENT." >> $Logfile
		echo "$date: pdp, APN & authentication are DIFFERENT." >> $Logfile2

		#Set APN
		for i in 1 2                                                                                                                 
		do
			echo "$date: Setting pdp, APN & authentication...." >> $Logfile
			echo "$date: Setting pdp, APN & authentication...." >> $Logfile2
			Status=$(/bin/at-cmd $ComPortSymLink AT+QICSGP=1,"$pdp",\"$APN\",\"$username\",\"$password\","$auth" | awk NR==2 | tr -d '\011\012\013\014\015\040') 
			
			if [ "$Status" = "OK" ]                                                                                                        
			then
				echo "$date: APN ,PDP,Auth is set Successfully." >> $Logfile
				echo "$date: Deactivating the pdp context using AT+QIDEACT=1." >> $Logfile
				echo "$date: APN ,PDP,Auth is set Successfully." >> $Logfile2
				echo "$date: Deactivating the pdp context using AT+QIDEACT=1." >> $Logfile2
				#Deactivate the pdp context.
				/bin/at-cmd $ComPortSymLink AT+QIDEACT=1
				
				sleep 1

				#Reboot/switch sim depending on the interface name.
				ModemReboot $InterfaceName $ComPortSymLink
				
				#Exit if the AddIfaceRunningstatus2 flag is set to 1. 
				CheckAddIfaceRunningstatus2
				
				break                                                                                                                     
			else                                                                                                                           
				sleep 3                                                                                                                    
			fi                                                                                                                           
		done 
		
		if [ "$Status" != "OK" ]
		then
			echo "$date:AT+QICSGP At command Status is $Status, status not OK when apn,pdp is not set Successfully" >> $Logfile
			echo "$date:AT+QICSGP At command Status is $Status, status not OK when apn,pdp is not set Successfully" >> $Logfile2
			
			#Reboot/switch sim depending on the interface name.
			ModemReboot $InterfaceName $ComPortSymLink
			
			#Exit if the AddIfaceRunningstatus2 flag is set to 1. 
			CheckAddIfaceRunningstatus2
	
		fi

	#If the pdp, APN & authentication are same.
	else
		echo "$date: pdp, APN & authentication are SAME." >> $Logfile
		echo "$date: pdp, APN & authentication are SAME." >> $Logfile2
		#Activate pdp context 1. Get response -- either OK/Error.
		for i in 1 2 3                                                                                                                    
		do
			Status=$(/bin/at-cmd $ComPortSymLink AT+QIACT=1 | awk NR==2 | tr -d '\011\012\013\014\015\040')
									 
			if [ "$Status" = "OK" ]                                                                                                        
			then
				echo "$date: AT+QIACT=1 = Activated pdp context 1." >> $Logfile
				echo "$date: AT+QIACT=1 = Activated pdp context 1." >> $Logfile2
				break                                                                                                                     
			else                                                                                                                           
				sleep 3                                                                                                                    
			fi                                                                                                                             
		done 
		
		#If the response of AT+QIACT=1 is error or if it has no response.
		if [ "$Status" != "OK" ]
		then
			echo "$date: The status of AT+QIACT=1 cmd is not OK & it is = "$Status >> $Logfile
			echo "$date: The status of AT+QIACT=1 cmd is not OK & it is = "$Status >> $Logfile2
			
			#echo "AT+QIDEACT=1 Deactivate the pdp context." >> $Logfile
			#Deactivate and then reboot
			#/bin/at-cmd $ComPortSymLink AT+QIDEACT=1
			#sleep 1
			#Reboot/switch sim depending on the interface name.
			#ModemReboot $InterfaceName $ComPortSymLink
			
		#If the response of AT+QIACT=1 is OK
		else
			#check if pdp is activated/not.
			for i in 1 2 3                                                                                                                    
			do	
				#To get only IP we use here (cut -d "," -f 4)
				Status=$(/bin/at-cmd $ComPortSymLink AT+QIACT? | awk NR==2 | cut -d "," -f 4 | tr -d '\011\012\013\014\015\040')
				Status=$(echo $Status | tr -d '"')
				echo "$date: The status of AT+QIACT? cmd is = $Status" >> $Logfile
				echo "$date: The status of AT+QIACT? cmd is = $Status" >> $Logfile2
				
				#For ipv4 -
				if [ "$pdp" = "1" ]
				then
					ipaddr=$(echo $Status | cut -d "," -f 4 | tr -d -c '.' | wc -c | tr -d '\011\012\013\014\015\040')
					echo "$date: It's an IPV4 address" >> $Logfile
					echo "$date: It's an IPV4 address" >> $Logfile2
					
					#ipv4 has 3 dots (.)                         
					if [ "$ipaddr" = "3" ]                                                                                                        
					then
						break
					else
						echo "$date: The IPv4 address obtained is incorrect. It has '$ipaddr' dots." >> $Logfile
						echo "$date: The IPv4 address obtained is incorrect. It has '$ipaddr' dots." >> $Logfile2
						#Reboot/switch sim depending on the interface name.
						#ModemReboot $InterfaceName $ComPortSymLink
					fi
				
				#For ipv6 -
				elif [ "$pdp" = "2" ]
				then
					ipaddr=$(echo $Status | cut -d "," -f 4 | cut -d ":" -f 1 | awk -F'"' '{print $2}' | tr -d '\011\012\013\014\015\040')
					echo "$date: It's an IPV6 address" >> $Logfile
					echo "$date: It's an IPV6 address" >> $Logfile2
					
					#ipv6 starting addr should be greater then 2000                         
					if [ "$ipaddr" -gt "2000" ]                                                                                                        
					then
						break
					else
						echo "$date: The IPv6 address obtained is incorrect. It has '$ipaddr' starting address." >> $Logfile
						echo "$date: The IPv6 address obtained is incorrect. It has '$ipaddr' starting address." >> $Logfile2
						#Reboot/switch sim depending on the interface name.
						#ModemReboot $InterfaceName $ComPortSymLink
					fi
				
				#For ipv4v6 -
				elif [ "$pdp" = "3" ]
				then
					ipaddr1=$(echo $Status | cut -d "," -f 4 | tr -d -c '.' | wc -c | tr -d '\011\012\013\014\015\040')
					ipaddr2=$(echo $Status | cut -d "," -f 5 | cut -d ":" -f 1 | tr -d '\011\012\013\014\015\040')
					echo "$date: It's an IPV4V6 address" >> $Logfile
					echo "$date: It's an IPV4V6 address" >> $Logfile2
					
					#ipv6 starting addr should be greater then 2000 & ipv4 has 3 dots (.)                        
					if [ "$ipaddr1" = "3" ] && [ "$ipaddr2" -gt "2000" ]                                                                                                    
					then
						break
					else
						echo "$date: The IPv6 address obtained is incorrect. It has '$ipaddr1' dots & '$ipaddr2' starting address." >> $Logfile
						echo "$date: The IPv6 address obtained is incorrect. It has '$ipaddr1' dots & '$ipaddr2' starting address." >> $Logfile2
						#Reboot/switch sim depending on the interface name.
						#ModemReboot $InterfaceName $ComPortSymLink
					fi
				
				#For wrong pdp
				else
					echo "$date: Wrong pdp set. Rebooting ..." >> $Logfile
					echo "$date: Wrong pdp set. Rebooting ..." >> $Logfile2
					#Reboot/switch sim depending on the interface name.
					ModemReboot $InterfaceName $ComPortSymLink
					
					#Exit if the AddIfaceRunningstatus2 flag is set to 1. 
					CheckAddIfaceRunningstatus2
				fi                                                                                                                         
			done
		fi
	fi
	
	exec 200>"$ComPortSymLink"
	flock -n 200
	
	#Get AltComPortSymLink for qnetdevctl.
	AltComPortSymLink=$(uci get modem.$InterfaceName.AltComPortSymLink)
	
	Status_ok=$(/bin/at-cmd "$ComPortSymLink" AT+QNETDEVCTL=1,1,1 | awk NR==2 | tr -d '\011\012\013\014\015\040')
	
	#If response is ok; then break.
	if [ "$Status_ok" = "OK" ]
	then
		echo "$date: AT+QNETDEVCTL=$Status_ok" >> $Logfile
		echo "$date: AT+QNETDEVCTL=$Status_ok" >> $Logfile2
		break 
	#If no response, then try again 3 times
	else
		sleep 2
		echo "$date: AT+QNETDEVCTL=$Status_ok" >> $Logfile
		echo "$date: AT+QNETDEVCTL=$Status_ok" >> $Logfile2
		
		for i in 1 2 3                                                                                                                   
		do
			Status=$(/bin/at-cmd "$ComPortSymLink" AT+QNETDEVCTL=1,1,1 | awk NR==2 | tr -d '\011\012\013\014\015\040')
			
			if [ "$Status" = "OK" ]
			then
				echo "$date: AT+QNETDEVCTL=$Status" >> $Logfile
				echo "$date: AT+QNETDEVCTL=$Status" >> $Logfile2
				
				#Set got_ok as 1, if received ok as response. So as not to switch to alt comport port.
				got_ok=1
				break 
			else
				sleep 2
				echo "$date: AT+QNETDEVCTL=$Status" >> $Logfile
				echo "$date: AT+QNETDEVCTL=$Status" >> $Logfile2
			fi
		done
		
		if [ "$got_ok" = "1" ]
		then
			break
		
		#If no response on comport, then switch to alt comport.
		else
			echo "$date: No response on AT+QNETDEVCTL; switching to alternate comport" >> $Logfile
			echo "$date: No response on AT+QNETDEVCTL; switching to alternate comport" >> $Logfile2
			
			for i in 1 2 3                                                                                                                   
			do
				Status_alt=$(/bin/at-cmd "$AltComPortSymLink" AT+QNETDEVCTL=1,1,1 | awk NR==2 | tr -d '\011\012\013\014\015\040')
				
				if [ "$Status_alt" = "OK" ]
				then
					echo "$date: AT+QNETDEVCTL=$Status_alt for AltComPort" >> $Logfile
					echo "$date: AT+QNETDEVCTL=$Status_alt for AltComPort" >> $Logfile2
					break 
				else
					sleep 2
