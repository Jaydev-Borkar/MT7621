AddNetworkInterface()
{
	InterfaceName="$1"
	status="$2"
	IPV6InterfaceName="$3"
	
	#Exit if the AddIfaceRunningstatus2 flag is set to 1. 
	CheckAddIfaceRunningstatus2
	
	#Run bandlock script
	$Updatebandlock "AddInterface_mod2"
	
	sleep 1
	
	#Check if xlat is enabled 
	Enablexlatsim1=$(uci get sysconfig.sysconfig.Enable464xlatSim1)
	Enablexlatsim2=$(uci get sysconfig.sysconfig.Enable464xlatSim2)
	
	echo "<AddInterface_mod2.sh><AddNetworkInterface> Enablexlatsim1=$Enablexlatsim1" >> $Logfile2
	echo "<AddInterface_mod2.sh><AddNetworkInterface> Enablexlatsim2=$Enablexlatsim2" >> $Logfile2
	
	if [ "$CellularOperationModelocal" = "dualcellularsinglesim" ]
	then
		if ([ "$Enablexlatsim1" = "1" ] && [ "$IPV6InterfaceName" = "wan6c1" ])
		then
			uci set network.${IPV6InterfaceName}_xlat=interface
			uci set network.${IPV6InterfaceName}_xlat.proto='464xlat'
			uci set network.${IPV6InterfaceName}_xlat.tunlink=$IPV6InterfaceName
			uci set network.${IPV6InterfaceName}_xlat.ip6prefix='64:ff9b::/96'
		elif ([ "$Enablexlatsim2" = "1" ] && [ "$IPV6InterfaceName" = "wan6c2" ]) 
		then
			uci set network.${IPV6InterfaceName}_xlat=interface
			uci set network.${IPV6InterfaceName}_xlat.proto='464xlat'
			uci set network.${IPV6InterfaceName}_xlat.tunlink=$IPV6InterfaceName
			uci set network.${IPV6InterfaceName}_xlat.ip6prefix='64:ff9b::/96'
		fi
	else
		if ([ "$Enablexlatsim1" = "1" ] && [ "$IPV6InterfaceName" = "wan6c1" ]) || ([ "$Enablexlatsim2" = "1" ] && [ "$IPV6InterfaceName" = "wan6c2" ]) 
		then
			uci set network.${IPV6InterfaceName}_xlat=interface
			uci set network.${IPV6InterfaceName}_xlat.proto='464xlat'
			uci set network.${IPV6InterfaceName}_xlat.tunlink=$IPV6InterfaceName
			uci set network.${IPV6InterfaceName}_xlat.ip6prefix='64:ff9b::/96'
		fi
	fi
	
	#cdcether
	if [ "$protocol" = "cdcether" ]
	then
		#IPV4
		if [ "$pdp" = "1" ] 				
		then
			uci set network."$InterfaceName"=interface
			uci set network."$InterfaceName".ifname="$ifname"
			uci set network."$InterfaceName".proto="dhcp"
			uci set network."$InterfaceName".metric="$Metric"
		#IPV6
		elif [ "$pdp" = "2" ]
		then 
			uci set network."$IPV6InterfaceName"=interface
			uci set network."$IPV6InterfaceName".ifname="$ifname"
			uci set network."$IPV6InterfaceName".proto="dhcpv6"
			#Need sourcefilter for dual modem ipv6
			uci set network."$IPV6InterfaceName".sourcefilter="0"
			uci set network."$IPV6InterfaceName".metric="$Metric" 
			uci set network."$IPV6InterfaceName".reqaddress="try" 
			uci set network."$IPV6InterfaceName".reqprefix="auto"
		#IPV4V6
		elif [ "$pdp" = "3" ] 
		then  
			uci set network."$InterfaceName"=interface
			uci set network."$InterfaceName".ifname="$ifname"
			uci set network."$InterfaceName".proto="dhcp"
			uci set network."$InterfaceName".metric="$Metric" 
			
			uci set network."$IPV6InterfaceName"=interface
			uci set network."$IPV6InterfaceName".ifname="$ifname"
			#Need sourcefilter for dual modem ipv6
			uci set network."$IPV6InterfaceName".sourcefilter="0"
			uci set network."$IPV6InterfaceName".proto="dhcpv6"
			uci set network."$IPV6InterfaceName".metric="$Metric" 
			uci set network."$IPV6InterfaceName".reqaddress="try" 
			uci set network."$IPV6InterfaceName".reqprefix="auto"
		fi
		
		uci commit network

		#Execute AT commands
		SetATCommands $InterfaceName $ComPortSymLink
		
		echo "<AddInterface_mod2.sh><AddNetworkInterface> SetATCommands done!" >> $Logfile2
		
	#QMI
	else
		if [ "$auth" = "1" ]
		then 
			 authentication=PAP
		elif [ "$auth" = "2" ]
		then
			 authentication=CHAP
		fi
		
		#IPV4
		if [ "$pdp" = "1" ] 				
		then		
			uci set network."$InterfaceName"=interface
			uci set network."$InterfaceName".ifname="$ifname"
			uci set network."$InterfaceName".proto="qmi"
			uci set network."$InterfaceName".device="/dev/$device"                                                                
			uci set network."$InterfaceName".apn="$APN"
			uci set network."$InterfaceName".pdptype="ipv4"                                                                
			uci set network."$InterfaceName".metric="$Metric"
			if [ "$auth" = "1" ] ||  [ "$auth" = "2" ]
			then
				uci set network."$InterfaceName".auth="$authentication"
				uci set network."$InterfaceName".username="$username"
				uci set network."$InterfaceName".password="$password"
			fi	
		#IPV6
		elif [ "$pdp" = "2" ]
		then 
			uci set network."$IPV6InterfaceName"=interface
			uci set network."$IPV6InterfaceName".ifname="$ifname"
			uci set network."$IPV6InterfaceName".proto="qmi"
			uci set network."$IPV6InterfaceName".apn="$APN"
			uci set network."$IPV6InterfaceName".metric="$Metric" 
			uci set network."$IPV6InterfaceName".device="/dev/$device"                                                                
			uci set network."$IPV6InterfaceName".pdptype="ipv6"                                                                
			uci set network."$IPV6InterfaceName".ipv6="1" 
	
			if [ "$auth" = "1" ] ||  [ "$auth" = "2" ]
			then
				uci set network."$IPV6InterfaceName".auth="$authentication"
				uci set network."$IPV6InterfaceName".username="$username"
				uci set network."$IPV6InterfaceName".password="$password"
			fi
		#IPV4V6
		elif [ "$pdp" = "3" ] 
		then  
			uci set network."$InterfaceName"=interface
			uci set network."$InterfaceName".ifname="$ifname"
			uci set network."$InterfaceName".proto="qmi"
			uci set network."$InterfaceName".device="/dev/$device"                                                                
			uci set network."$InterfaceName".apn="$APN"
			uci set network."$InterfaceName".pdptype="ipv4v6"                                                                
			uci set network."$InterfaceName".metric="$Metric"
			if [ "$auth" = "1" ] ||  [ "$auth" = "2" ]
			then
				uci set network."$InterfaceName".auth="$authentication"
				uci set network."$InterfaceName".username="$username"
				uci set network."$InterfaceName".password="$password"
			fi
		fi	
		
		uci commit network

		#Execute AT commands
		SetATCommandsQMI $InterfaceName $ComPortSymLink
		
		echo "<AddInterface_mod2.sh><AddNetworkInterface> SetATCommandsQMI done!" >> $Logfile2
		
	fi 
	
	#Run operatorlock Function
	UpdateOperatorLock
	
	#Exit if the AddIfaceRunningstatus2 flag is set to 1. 
	CheckAddIfaceRunningstatus2
	
	ifup "$InterfaceName" > /dev/null 2>&1
	sleep 1
	ifup "$IPV6InterfaceName" > /dev/null 2>&1
	sleep 1
	mwan3 ifup "$InterfaceName" > /dev/null 2>&1
	sleep 1
	mwan3 ifup "$IPV6InterfaceName" > /dev/null 2>&1
	
	echo "<AddInterface_mod2.sh><AddNetworkInterface> $InterfaceName protocol=$protocol pdp=$pdp" >> $Logfile2
	echo "<AddInterface_mod2.sh><AddNetworkInterface> $InterfaceName ifup done!" >> $Logfile2
	echo "<AddInterface_mod2.sh><AddNetworkInterface> $IPV6InterfaceName ifup done!" >> $Logfile2
	echo "status=Enabled" > "$AddIfaceStatusFile"
	
	echo "<AddInterface_mod2.sh><AddNetworkInterface> <SimLeds>" >> $Logfile2
	
	#Glow the sim leds.	
	SimLeds $InterfaceName $status
	
	#to glow signal strength led's
	/root/InterfaceManager/script/Update_Analytics_data.sh > /dev/null 2>&1
	
}

