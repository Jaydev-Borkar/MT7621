		for i in 1 2 3                                                                                                                    
		do
			Status=$(/bin/at-cmd $ComPortSymLink AT+QIACT=1 | awk NR==2 | tr -d '\011\012\013\014\015\040')
									 
			if [ "$Status" = "OK" ]                                                                                                        
			then
